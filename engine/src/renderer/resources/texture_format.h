#pragma once

namespace ptgn {

enum class TextureFormat {
	// ---------------------------------------------------------------------
	// Color (8-bit normalized)
	// ---------------------------------------------------------------------
	R8,
	RG8,
	RGBA8,

	RGBA8_SRGB,

	// ---------------------------------------------------------------------
	// Color (16-bit / float)
	// ---------------------------------------------------------------------
	R16F,
	RG16F,
	RGBA16F,

	R32F,
	RG32F,
	RGBA32F,

	// ---------------------------------------------------------------------
	// HDR / lighting
	// ---------------------------------------------------------------------
	RGB10_A2,
	R11G11B10F,

	// ---------------------------------------------------------------------
	// Depth / stencil
	// ---------------------------------------------------------------------
	Depth16,
	Depth24,
	Depth32F,

	Depth24_Stencil8,
	Depth32F_Stencil8,

	// ---------------------------------------------------------------------
	// Special / utility
	// ---------------------------------------------------------------------
	Stencil8
};

} // namespace ptgn